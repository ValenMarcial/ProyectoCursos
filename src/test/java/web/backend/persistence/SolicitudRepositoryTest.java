package web.backend.persistence;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import web.backend.api.dto.IniciarSolicitudRequest;
import web.backend.persistence.SolicitudRepository.SolicitudRegistrada;

class SolicitudRepositoryTest {
    private JdbcTemplate jdbcTemplate;
    private SolicitudRepository repository;
    private IniciarSolicitudRequest request;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:solicitud-repo-" + System.nanoTime()
                        + ";MODE=PostgreSQL;DB_CLOSE_DELAY=1000", "sa", "");
        jdbcTemplate = new JdbcTemplate(dataSource);
        repository = new SolicitudRepository(jdbcTemplate);
        crearTablas();
        request = request("Empresa Ejemplo");
    }

    @Test
    void registraSolicitudYReutilizaEmpresaNormalizada() {
        SolicitudRegistrada primera = repository.registrar("solicitud-1", request);
        SolicitudRegistrada segunda = repository.registrar("solicitud-2", request("  empresa ejemplo  "));

        assertEquals(primera.getEmpresaId(), segunda.getEmpresaId());
        assertEquals(1L, contar("empresas"));
        assertEquals(2L, contar("solicitudes"));
        assertEquals("BPMN", jdbcTemplate.queryForObject(
                "SELECT tematica FROM solicitudes WHERE id = ?", String.class, primera.getSolicitudId()));
        assertNull(jdbcTemplate.queryForObject(
                "SELECT contacto_telefono FROM solicitudes WHERE id = ?", String.class, primera.getSolicitudId()));
    }

    @Test
    void vinculaInstanciaSoloUnaVez() {
        SolicitudRegistrada solicitud = repository.registrar("solicitud-1", request);

        repository.vincularInstancia(solicitud.getSolicitudId(), "process-1");

        assertEquals("process-1", jdbcTemplate.queryForObject(
                "SELECT instancia_flowable_id FROM solicitudes WHERE id = ?",
                String.class, solicitud.getSolicitudId()));
        assertEquals("iniciada", jdbcTemplate.queryForObject(
                "SELECT integracion_flowable_estado FROM solicitudes WHERE id = ?",
                String.class, solicitud.getSolicitudId()));
        assertThrows(IllegalStateException.class,
                () -> repository.vincularInstancia(solicitud.getSolicitudId(), "process-2"));
    }

    @Test
    void eliminaSoloSolicitudesSinInstancia() {
        SolicitudRegistrada pendiente = repository.registrar("solicitud-1", request);
        SolicitudRegistrada iniciada = repository.registrar("solicitud-2", request);
        repository.vincularInstancia(iniciada.getSolicitudId(), "process-1");

        repository.eliminarSolicitud(pendiente.getSolicitudId());
        repository.eliminarSolicitud(iniciada.getSolicitudId());

        assertEquals(0L, contarSolicitud(pendiente.getSolicitudId()));
        assertEquals(1L, contarSolicitud(iniciada.getSolicitudId()));
    }

    private IniciarSolicitudRequest request(String empresaNombre) {
        IniciarSolicitudRequest value = new IniciarSolicitudRequest();
        value.setEmpresaNombre(empresaNombre);
        value.setContactoNombre("Ana Pérez");
        value.setContactoEmail("ana@example.com");
        value.setContactoTelefono("   ");
        value.setTematica("BPMN");
        value.setDescripcion("Curso de prueba");
        value.setParticipantesEstimados(12);
        value.setFechasPreferidas("Marzo 2027");
        return value;
    }

    private void crearTablas() {
        jdbcTemplate.execute("CREATE TABLE empresas ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "nombre VARCHAR(255) NOT NULL UNIQUE, "
                + "cantidad_empleados INT, "
                + "nombre_normalizado VARCHAR(255) GENERATED ALWAYS AS (lower(trim(nombre))))");
        jdbcTemplate.execute("CREATE UNIQUE INDEX empresas_nombre_normalizado_unique "
                + "ON empresas (nombre_normalizado)");
        jdbcTemplate.execute("CREATE TABLE solicitudes ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "empresa_id BIGINT NOT NULL, "
                + "business_key VARCHAR(255) NOT NULL UNIQUE, "
                + "tematica VARCHAR(255) NOT NULL, "
                + "descripcion VARCHAR(1000) NOT NULL, "
                + "contacto_nombre VARCHAR(255), "
                + "contacto_email VARCHAR(255), "
                + "contacto_telefono VARCHAR(255), "
                + "participantes_estimados INT, "
                + "fechas_preferidas VARCHAR(500), "
                + "instancia_flowable_id VARCHAR(64) UNIQUE, "
                + "integracion_flowable_estado VARCHAR(20) NOT NULL DEFAULT 'pendiente', "
                + "creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
    }

    private long contar(String tabla) {
        return jdbcTemplate.queryForObject("SELECT count(*) FROM " + tabla, Long.class);
    }

    private long contarSolicitud(Long solicitudId) {
        return jdbcTemplate.queryForObject(
                "SELECT count(*) FROM solicitudes WHERE id = ?", Long.class, solicitudId);
    }
}
