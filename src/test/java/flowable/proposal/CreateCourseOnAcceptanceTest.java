package flowable.proposal;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import java.lang.reflect.Proxy;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Date;
import java.util.HashMap;
import java.util.Map;

import org.flowable.common.engine.api.FlowableException;
import org.flowable.engine.delegate.DelegateExecution;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class CreateCourseOnAcceptanceTest {
    private String url;
    private CreateCourseOnAcceptance delegate;

    @BeforeEach
    void setUp() throws SQLException {
        url = "jdbc:h2:mem:course-link-" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
        delegate = new CreateCourseOnAcceptance(() -> {
            try {
                return DriverManager.getConnection(url, "sa", "");
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        });
        try (Connection connection = DriverManager.getConnection(url, "sa", "");
                Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE cursos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, empresa_id BIGINT NOT NULL, "
                    + "nombre VARCHAR(200) NOT NULL, descripcion VARCHAR(2000), programa VARCHAR(100), "
                    + "presupuesto INT, fecha_inicio DATE, fecha_fin DATE, "
                    + "instancia_flowable_id VARCHAR(64) UNIQUE, estado VARCHAR(30) DEFAULT 'en_preparacion')");
            statement.execute("CREATE TABLE solicitudes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, empresa_id BIGINT NOT NULL, "
                    + "tematica VARCHAR(200), descripcion VARCHAR(2000), curso_id BIGINT UNIQUE)");
            statement.execute("INSERT INTO solicitudes (empresa_id, tematica, descripcion) "
                    + "VALUES (7, 'BPMN', 'Curso de BPMN')");
        }
    }

    @Test
    void creaCursoConLaFechaAcordadaYNoDuplicaAlReintentarLaActividad() throws SQLException {
        Map<String, Object> variables = variables(1L);

        delegate.execute(execution("proc-1", variables));
        delegate.execute(execution("proc-1", variables));

        try (Connection connection = DriverManager.getConnection(url, "sa", "");
                Statement statement = connection.createStatement()) {
            var cursos = statement.executeQuery("SELECT COUNT(*) FROM cursos");
            cursos.next();
            assertEquals(1, cursos.getInt(1));
            var curso = statement.executeQuery(
                    "SELECT c.nombre, c.programa, c.presupuesto, c.empresa_id, c.id, c.fecha_inicio, c.estado, s.curso_id "
                            + "FROM cursos c JOIN solicitudes s ON s.curso_id = c.id");
            curso.next();
            assertEquals("BPMN", curso.getString("nombre"));
            assertEquals("Cloud", curso.getString("programa"));
            assertEquals(5000, curso.getInt("presupuesto"));
            assertEquals(7L, curso.getLong("empresa_id"));
            assertEquals("2027-01-15", curso.getDate("fecha_inicio").toString());
            assertEquals("en_preparacion", curso.getString("estado"));
            assertEquals(curso.getLong("id"), variables.get("cursoId"));
        }
    }

    @Test
    void rechazaSolicitudInexistente() {
        assertThrows(FlowableException.class, () -> delegate.execute(execution("proc-2", variables(99L))));
    }

    @Test
    void noUsaFechaPosibleSiFaltaLaFechaAcordada() {
        Map<String, Object> variables = variables(1L);
        variables.remove("fechaInicio");

        assertThrows(FlowableException.class, () -> delegate.execute(execution("proc-3", variables)));
    }

    @Test
    void rechazaFechaDeInicioPosteriorAlFinPropuestoSinCrearElCurso() throws SQLException {
        Map<String, Object> variables = variables(1L);
        variables.put("fechaInicio", "2027-12-01");

        assertThrows(FlowableException.class, () -> delegate.execute(execution("proc-4", variables)));
        try (Connection connection = DriverManager.getConnection(url, "sa", "");
                Statement statement = connection.createStatement()) {
            var cursos = statement.executeQuery("SELECT COUNT(*) FROM cursos");
            cursos.next();
            assertEquals(0, cursos.getInt(1));
        }
    }

    @Test
    void aceptaInicioElMismoDiaDelFinPropuesto() {
        Map<String, Object> variables = variables(1L);
        variables.put("fechaInicio", new java.sql.Date(1_800_900_000_000L).toString());

        delegate.execute(execution("proc-5", variables));

        assertEquals(1L, variables.get("cursoId"));
    }

    private Map<String, Object> variables(long solicitudId) {
        Map<String, Object> variables = new HashMap<>();
        variables.put("solicitudId", solicitudId);
        variables.put("programa", "Cloud");
        variables.put("presupuesto", 5000L);
        variables.put("fechaInicioPosible", new Date(1_800_432_000_000L));
        variables.put("fechaInicio", "2027-01-15T09:00:00");
        variables.put("fechaFinPropuesta", new Date(1_800_900_000_000L));
        return variables;
    }

    private DelegateExecution execution(String processInstanceId, Map<String, Object> variables) {
        return (DelegateExecution) Proxy.newProxyInstance(getClass().getClassLoader(),
                new Class<?>[] {DelegateExecution.class}, (proxy, method, args) -> {
                    switch (method.getName()) {
                        case "getVariable":
                            return variables.get(args[0]);
                        case "setVariable":
                            variables.put((String) args[0], args[1]);
                            return null;
                        case "getProcessInstanceId":
                            return processInstanceId;
                        default:
                            throw new UnsupportedOperationException(method.getName());
                    }
                });
    }
}
